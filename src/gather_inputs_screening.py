## Really all this needs to do is convert the pdb files to pdb pockets

import pandas as pd
from pathlib import Path
import argparse
from tqdm import tqdm

def convert_pdb(
    pdb: Path,  
    output_dir: Path,
    substrate: str
):
    """
    Convert pdb file into acceptable format for pocket extraction
    Save the converted pdb file to a new directory

    Args:
        pdb: Path to the pdb file
        df: DataFrame containing the Dock Index and pdb_id
        output_dir: Path to the directory to save the converted pdb file

    Returns:
        None
    """

    pdb_index = pdb.stem.split("_")[0]
    output_path = output_dir / f"{pdb_index}.pdb"

    protein_lines = []
    ligand_lines = []
    ligand_atoms = []
    with open(pdb, "r") as f:
        lines = f.readlines()

    ## Remove first 2 lines
    lines = lines[2:]

    ## Collect all lines until "HEM" is found
    ## Change "ATOM" to "HETATM" in all lines with "HEM"
    lig_found = False
    ligand_break = len(lines)  # Default to end of file if no ligand found
    for i, line in enumerate(lines):
        if "LIG B" in line and not lig_found:
            lig_found = True
            ligand_break = i
            ligand_lines.append(line)
            ligand_atoms.append(line[7:12].strip())

        elif "LIG B" in line and lig_found:
            ligand_lines.append(line)
            ligand_atoms.append(line[7:12].strip())

        elif "ATOM" in line:
            protein_lines.append(line)

    ## Final loop through lines to collect CONECT lines for ligand atoms
    ligand_atoms = list(set(ligand_atoms))
    for i, line in enumerate(lines[ligand_break:]):
        if "CONECT" in line:
            atoms = [atom.strip() for atom in line.split(" ")]
            if any(atom in ligand_atoms for atom in atoms):
                ligand_lines.append(line)
        elif "MASTER" in line:
            ligand_lines.append(line)

    ## Write to a new pdb file
    with open(output_path, "w") as f:
        for line in protein_lines:
            f.write(line)

        f.write("END\n")
        f.write(f"REMARK SMILES {substrate}\n")
        f.write(f"COMPND {pdb_index}\n")
        f.write("AUTHOR GENERATED BY OPEN BABEL 3.1.0\n")
        for line in ligand_lines:
            f.write(line)
        f.write("END\n")

def argparser():
    parser = argparse.ArgumentParser()
    parser.add_argument("-pdb-dir", type=Path, required=True)
    parser.add_argument("-output-dir", type=Path, required=True)
    parser.add_argument("-data-df", type=Path, required=True)
    parser.add_argument("-substrate-file", type=Path, required=True)

    return parser.parse_args()

def main():
    args = argparser()

    pdb_dir = args.pdb_dir
    prepared_data_dir = args.output_dir
    prepared_data_dir.mkdir(parents=True, exist_ok=True)
    complex_dir = prepared_data_dir / "Structure" / "complex"
    complex_dir.mkdir(parents=True, exist_ok=True)

    data_df = pd.read_csv(args.data_df)
    substrate_df = pd.read_csv(args.substrate_file)

    rows_to_rem = []
    for idx, row in tqdm(data_df.iterrows(), desc="Processing data", total=len(data_df)):
        pdb_id = row["Dock Index"]
        pdb_path = pdb_dir / f"{pdb_id}_model_0.pdb"
        substrate_id = row["Substrate Index"]
        substrate = substrate_df.iloc[substrate_id]["Substrate_SMILES"]

        if not pdb_path.is_file():
            print(f"Missing Boltz output: {pdb_path}")
            rows_to_rem.append(idx)
            continue

        try:
            convert_pdb(pdb_path, complex_dir, substrate)
        except Exception as e:
            print(f"Error converting pdb file {pdb_path}: {e}")
            rows_to_rem.append(idx)

    data_df = data_df.drop(index=rows_to_rem)
    out_path = prepared_data_dir / "data.csv"
    data_df.to_csv(out_path, index=False)
    print(f"Wrote {len(data_df)} rows to {out_path} (dropped {len(rows_to_rem)})")
    if len(data_df) == 0:
        print("Warning: no rows remaining after filtering")

    print("Done")

if __name__ == "__main__":
    main()